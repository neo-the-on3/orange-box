// Command stubgen writes Unimplemented, a StrictServerInterface whose every
// operation returns ErrNotImplemented. Handlers embed it and override the
// operations they implement, so a new operation in the spec compiles and
// answers 501 until someone fills it in.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
)

func main() {
	in := flag.String("in", "api.gen.go", "generated oapi-codegen file")
	out := flag.String("out", "stubs.gen.go", "output file")
	flag.Parse()

	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, *in, nil, 0)
	if err != nil {
		log.Fatal(err)
	}
	var methods []*ast.Field
	ast.Inspect(f, func(n ast.Node) bool {
		ts, ok := n.(*ast.TypeSpec)
		if !ok || ts.Name.Name != "StrictServerInterface" {
			return true
		}
		methods = ts.Type.(*ast.InterfaceType).Methods.List
		return false
	})
	if len(methods) == 0 {
		log.Fatal("StrictServerInterface not found")
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by stubgen from %s. DO NOT EDIT.\n\n", "api.gen.go")
	fmt.Fprintf(&b, "package %s\n\nimport \"context\"\n\n", f.Name.Name)
	b.WriteString("// Unimplemented answers every operation with ErrNotImplemented (501).\n")
	b.WriteString("type Unimplemented struct{}\n\n")
	b.WriteString("var _ StrictServerInterface = Unimplemented{}\n")
	for _, m := range methods {
		name := m.Names[0].Name
		ft := m.Type.(*ast.FuncType)
		req := ft.Params.List[1].Type.(*ast.Ident).Name
		resp := ft.Results.List[0].Type.(*ast.Ident).Name
		fmt.Fprintf(&b, "\n// %s returns ErrNotImplemented.\nfunc (Unimplemented) %s(context.Context, %s) (%s, error) {\n\treturn nil, ErrNotImplemented\n}\n", name, name, req, resp)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil { //nolint:gosec // generated source, world-readable like the rest of the repo
		log.Fatal(err)
	}
}
